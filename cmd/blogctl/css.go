package main

import (
	"errors"
	"flag"
	"fmt"
	"io"

	"github.com/elmerred09/blog/internal/content"
)

const cssUsage = "usage: blogctl css\n\n" +
	"Writes the stylesheet for syntax-highlighted code in rendered posts to stdout.\n" +
	"make chroma-css writes it to web/app/chroma.css.\n"

const cssHeader = "/* Generated by blogctl css (make chroma-css). Do not edit. */\n\n"

func runCSS(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("css", flag.ContinueOnError)
	flags.Usage = func() { _, _ = fmt.Fprint(flags.Output(), cssUsage) }
	if err := flags.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	if flags.NArg() != 0 {
		flags.Usage()
		return errors.New("css: takes no arguments")
	}

	if _, err := io.WriteString(stdout, cssHeader); err != nil {
		return fmt.Errorf("write css: %w", err)
	}
	return content.WriteCSS(stdout)
}
