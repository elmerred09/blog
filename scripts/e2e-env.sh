#!/usr/bin/env bash
# Writes the gitignored web/e2e/.env.e2e for the Playwright suite: a fresh
# Ed25519 keypair and Better Auth secret on every run, GitHub id 1 as the only
# admin, and the local RustFS settings. web/playwright.config.ts reads it and
# hands each server its part. One file holds both the API's and Next's
# variables; each ignores the other's.
# The ports and URLs here are the suite's own (API :8081, Next :3100), so a
# dev stack on :8080 and :3000 keeps running. Never touches .env or
# web/.env.local. The PEM keys are written on one line as in
# scripts/admin-keys.sh.
#
# Usage: scripts/e2e-env.sh <database url>  (make e2e passes the blog_e2e one)
set -euo pipefail

cd "$(dirname "$0")/.."

database_url="${1:-}"
if [[ -z "$database_url" ]]; then
  echo "usage: scripts/e2e-env.sh <database url>" >&2
  exit 1
fi

# shellcheck source-path=SCRIPTDIR/.. source=deploy/rustfs/local.env
. deploy/rustfs/local.env

s3_host=127.0.0.1:9000
api_port=8081
web_port=3100
github_id=1

umask 077
dir=$(mktemp -d)
trap 'rm -rf "$dir"' EXIT

openssl genpkey -algorithm ED25519 -out "$dir/private.pem"
openssl pkey -in "$dir/private.pem" -pubout -out "$dir/public.pem"

one_line() { awk '{printf "%s\\n", $0}' "$1"; }

cat > "$dir/env" <<EOF
# Generated by scripts/e2e-env.sh on every make e2e. Test-only keys.

# Go API
DATABASE_URL="$database_url"
HTTP_ADDR="127.0.0.1:$api_port"
ADMIN_JWT_PUBLIC_KEY="$(one_line "$dir/public.pem")"
ADMIN_SUBJECTS="github:$github_id"
S3_ENDPOINT="$s3_host"
S3_REGION="$S3_REGION"
S3_BUCKET="$S3_BUCKET"
S3_ACCESS_KEY="$RUSTFS_ACCESS_KEY"
S3_SECRET_KEY="$RUSTFS_SECRET_KEY"
S3_PUBLIC_BASE_URL="http://$s3_host/$S3_BUCKET"

# Next. Every key web/.env.local can set must be here: Next loads that file
# under next start too, and only process env wins over it.
API_URL="http://127.0.0.1:$api_port"
ADMIN_GITHUB_IDS="$github_id"
ADMIN_JWT_PRIVATE_KEY="$(one_line "$dir/private.pem")"
BETTER_AUTH_SECRET="$(openssl rand -hex 32)"
# http://, so Better Auth's cookie names have no __Secure- prefix.
BETTER_AUTH_URL="http://localhost:$web_port"
# Never contacted: the suite signs in with minted cookies (e2e/auth.ts).
GITHUB_CLIENT_ID="e2e-unused"
GITHUB_CLIENT_SECRET="e2e-unused"
EOF

mkdir -p web/e2e
mv "$dir/env" web/e2e/.env.e2e
echo "wrote web/e2e/.env.e2e"
