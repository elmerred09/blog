#!/usr/bin/env bash
# Writes the gitignored .env (sourced by make api) and web/.env.local (loaded
# by Next) from one GitHub user id, so the two admin allowlists can't drift.
# The PEM keys go on one line with \n for each newline, in double quotes: the
# API's config unescapes them, and Next's env loader expands them. Refuses to
# overwrite either file.
#
# Usage: scripts/admin-keys.sh <github user id>  (or make admin-keys)
set -euo pipefail

cd "$(dirname "$0")/.."

github_id="${1:-}"
if [[ ! "$github_id" =~ ^[0-9]+$ ]]; then
  echo "usage: make admin-keys ADMIN_GITHUB_ID=<numeric github user id>" >&2
  exit 1
fi
if [[ -e .env || -e web/.env.local ]]; then
  echo "refusing to overwrite .env or web/.env.local" >&2
  exit 1
fi

# RUSTFS_ACCESS_KEY, RUSTFS_SECRET_KEY, S3_BUCKET, S3_REGION: the same file
# compose.yaml gives RustFS.
# shellcheck source-path=SCRIPTDIR/.. source=deploy/rustfs/local.env
. deploy/rustfs/local.env

# The host side of the rustfs port mapping in compose.yaml.
s3_host=127.0.0.1:9000

umask 077
dir=$(mktemp -d)
trap 'rm -rf "$dir"' EXIT

openssl genpkey -algorithm ED25519 -out "$dir/private.pem"
openssl pkey -in "$dir/private.pem" -pubout -out "$dir/public.pem"

# one_line prints a PEM file on one line, each newline written as \n.
one_line() { awk '{printf "%s\\n", $0}' "$1"; }

cat > "$dir/env" <<EOF
# Generated by scripts/admin-keys.sh. Local only.
ADMIN_JWT_PUBLIC_KEY="$(one_line "$dir/public.pem")"
ADMIN_SUBJECTS="github:$github_id"
S3_ENDPOINT="$s3_host"
S3_REGION="$S3_REGION"
S3_BUCKET="$S3_BUCKET"
S3_ACCESS_KEY="$RUSTFS_ACCESS_KEY"
S3_SECRET_KEY="$RUSTFS_SECRET_KEY"
S3_PUBLIC_BASE_URL="http://$s3_host/$S3_BUCKET"
EOF

cat > "$dir/env.local" <<EOF
# Generated by scripts/admin-keys.sh. Local only.
ADMIN_GITHUB_IDS="$github_id"
ADMIN_JWT_PRIVATE_KEY="$(one_line "$dir/private.pem")"
EOF

# Both files are complete before either is moved into place.
mv "$dir/env" .env
mv "$dir/env.local" web/.env.local
echo "wrote .env and web/.env.local"
